#!/usr/bin/env python3
"""finalize.py FILE [--author NAME] [--title TITLE] [--check]

Normalizes the metadata of a docx, pptx or xlsx that a script produced, by
editing its OOXML zip directly (nothing to install):

- docProps/core.xml: creator and lastModifiedBy become the author (default
  "Elías De La Cruz"); the title is set when given; a description, subject or
  keywords that only name the generating library is emptied.
- docProps/app.xml: an Application or AppVersion that names python-docx,
  python-pptx, openpyxl or another library is removed. A value that came from
  Elias's own template stays as it was; nothing is invented.

It then reads the file back and fails if any library fingerprint remains in
docProps. `--check` only reports. The document body is never touched.
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import sys
import tempfile
import zipfile

AUTHOR = "Elías De La Cruz"
LIBRARY = re.compile(r"python-docx|python-pptx|openpyxl|xlsxwriter|docx4j|aspose|pandoc|libreoffice-python|"
                     r"generated by|created by python", re.I)
CORE_NS = {
    "creator": "dc", "lastModifiedBy": "cp", "title": "dc", "description": "dc", "subject": "dc", "keywords": "cp",
}


def fingerprints(path: str) -> list[str]:
    with zipfile.ZipFile(path) as z:
        out = []
        for name in ("docProps/core.xml", "docProps/app.xml", "docProps/custom.xml"):
            if name in z.namelist():
                text = z.read(name).decode("utf-8", "ignore")
                out += [f"{name}: {m.group(0)}" for m in LIBRARY.finditer(text)]
        return out


def set_core(xml: str, field: str, value: str) -> str:
    prefix = CORE_NS[field]
    tag = f"{prefix}:{field}"
    value = value.replace("&", "&amp;").replace("<", "&lt;")
    pattern = re.compile(rf"<{tag}(\s[^>]*)?>.*?</{tag}>|<{tag}(\s[^>]*)?/>", re.S)
    if pattern.search(xml):
        return pattern.sub(f"<{tag}>{value}</{tag}>", xml, count=1)
    return xml.replace("</cp:coreProperties>", f"<{tag}>{value}</{tag}></cp:coreProperties>", 1)


def fix_core(xml: str, author: str, title: str | None) -> str:
    xml = set_core(xml, "creator", author)
    xml = set_core(xml, "lastModifiedBy", author)
    if title:
        xml = set_core(xml, "title", title)
    for field in ("description", "subject", "keywords"):
        prefix = CORE_NS[field]
        m = re.search(rf"<{prefix}:{field}>(.*?)</{prefix}:{field}>", xml, re.S)
        if m and LIBRARY.search(m.group(1)):
            xml = set_core(xml, field, "")
    return xml


def fix_app(xml: str) -> str:
    for tag in ("Application", "AppVersion", "Company"):
        m = re.search(rf"<{tag}>(.*?)</{tag}>", xml, re.S)
        if m and LIBRARY.search(m.group(1)):
            xml = xml.replace(m.group(0), "")
    return xml


def finalize(path: str, author: str, title: str | None) -> None:
    fd, tmp = tempfile.mkstemp(suffix=os.path.splitext(path)[1], dir=os.path.dirname(os.path.abspath(path)))
    os.close(fd)
    with zipfile.ZipFile(path) as src, zipfile.ZipFile(tmp, "w") as dst:
        for item in src.infolist():
            data = src.read(item.filename)
            if item.filename == "docProps/core.xml":
                data = fix_core(data.decode("utf-8"), author, title).encode("utf-8")
            elif item.filename == "docProps/app.xml":
                data = fix_app(data.decode("utf-8")).encode("utf-8")
            dst.writestr(item, data)
    shutil.move(tmp, path)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="finalize.py")
    ap.add_argument("file")
    ap.add_argument("--author", default=AUTHOR)
    ap.add_argument("--title")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    if not a.file.lower().endswith((".docx", ".pptx", ".xlsx")):
        print("finalize: only docx, pptx and xlsx", file=sys.stderr)
        return 2
    if not a.check:
        finalize(a.file, a.author, a.title)
    left = fingerprints(a.file)
    with zipfile.ZipFile(a.file) as z:
        core = z.read("docProps/core.xml").decode("utf-8", "ignore") if "docProps/core.xml" in z.namelist() else ""
    creator = re.search(r"<dc:creator>(.*?)</dc:creator>", core)
    print(f"{a.file}\n  creator: {creator.group(1) if creator else '(none)'}; "
          + ("library fingerprints left: " + "; ".join(left) if left else "no library fingerprints"))
    return 1 if left else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
